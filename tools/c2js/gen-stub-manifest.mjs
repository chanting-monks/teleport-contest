#!/usr/bin/env node
// gen-stub-manifest.mjs — generate js/translated/stub-manifest.js at
// build time (UNWEDGE_PLAN Q2).
//
// Why: js/c2js-runtime/autostub.js used to re-read every translated
// module (12+ MB) and regex-scan it AT EVERY ENGINE STARTUP to find
// call-position identifiers that need globalThis no-op stubs —
// ~200 ms of the leaderboard's startup intercept, and silently
// skipped in browsers (no node:fs), so node and browser ran with
// different effective stub sets.  This tool runs the same scan once,
// at build time, and emits the candidate list as a tiny ES module
// the runtime imports in any environment.
//
// The scan logic MUST stay behaviorally identical to the legacy
// fallback in js/c2js-runtime/autostub.js (which remains as a warned
// degradation path when the manifest is missing).  The one filter
// that stays at runtime is the `typeof globalThis[name] !==
// 'undefined'` check — it is load-order dependent (real impls like
// atoi are pre-installed by allmain.js and must not be clobbered).
//
// Usage:
//   node tools/c2js/gen-stub-manifest.mjs            # scan js/translated, write manifest
//   import { generateStubManifest } from './gen-stub-manifest.mjs'  (build-engine)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const RESERVED = new Set([
    'if', 'for', 'while', 'switch', 'return', 'function',
    'typeof', 'new', 'do', 'catch', 'else', 'case',
    'continue', 'break', 'throw', 'await', 'async',
    'let', 'const', 'var', 'in', 'of', 'try', 'finally',
    'instanceof', 'void', 'delete', 'this', 'super',
]);

export function computeStubNames(translatedDir) {
    const files = readdirSync(translatedDir)
        .filter((f) => f.endsWith('.js') && f !== 'stub-manifest.js');
    const declared = new Set();
    const sources = new Map();
    for (const f of files) {
        const src = readFileSync(join(translatedDir, f), 'utf8');
        sources.set(f, src);
        for (const m of src.matchAll(/(?:^|\n)export (?:async\s+)?function ([A-Za-z_][A-Za-z0-9_]*)/g)) declared.add(m[1]);
        for (const m of src.matchAll(/(?:^|\n)export const ([A-Za-z_][A-Za-z0-9_]*)/g)) declared.add(m[1]);
        for (const m of src.matchAll(/import\s*\{([^}]+)\}/g)) {
            for (const name of m[1].split(',').map((s) => s.trim()).filter((s) => s.length)) {
                for (const p of name.split(/\s+as\s+/)) declared.add(p);
            }
        }
    }
    const names = new Set();
    for (const src of sources.values()) {
        for (const m of src.matchAll(/(?<![\w$.])([a-z_][A-Za-z0-9_]*)\s*\(/g)) {
            const name = m[1];
            if (declared.has(name)) continue;
            if (RESERVED.has(name)) continue;
            names.add(name);
        }
    }
    return [...names].sort();
}

export function generateStubManifest(translatedDir) {
    const names = computeStubNames(translatedDir);
    const body = `// stub-manifest.js — GENERATED by tools/c2js/gen-stub-manifest.mjs.
// Candidate names for globalThis no-op stubs: identifiers appearing
// at call position in translator output that no translated module
// declares or imports.  Consumed by js/c2js-runtime/autostub.js
// (which still skips any name already defined on globalThis at
// install time).  Regenerated by build-engine after every build.
export const STUB_NAMES = ${JSON.stringify(names, null, 0).replace(/","/g, '",\n"')};
`;
    writeFileSync(join(translatedDir, 'stub-manifest.js'), body);
    return names.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const root = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
    const dir = join(root, 'js/translated');
    const n = generateStubManifest(dir);
    console.log(`stub-manifest: ${n} candidate names → ${join(dir, 'stub-manifest.js')}`);
}
